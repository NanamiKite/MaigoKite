// Generate transport types and standalone validators from the actual FastAPI routes.
// Does not start Core, read a user database, call a model or run tests.
import { execFileSync } from 'node:child_process'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'
import Ajv2020 from 'ajv/dist/2020.js'
import standalone from 'ajv/dist/standalone/index.js'
import { build } from 'esbuild'

const web = fileURLToPath(new URL('..', import.meta.url))
const root = path.dirname(web)
const python =
  process.env.MAIGOKITE_PYTHON ||
  path.join(root, '.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python')
const document = JSON.parse(
  execFileSync(python, ['-B', '-m', 'agent.api.export_contracts'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
    env: { ...process.env, PYTHONPATH: path.join(root, 'python'), PYTHONDONTWRITEBYTECODE: '1' },
  }),
)
const names = [
  'ConversationResponse',
  'ConversationsResponse',
  'TaskResponse',
  'TasksResponse',
  'TaskResultResponse',
  'ApprovalResponse',
  'ApprovalsResponse',
  'AuthorizationResponse',
  'AuthorizationsResponse',
  'MessageResponse',
  'MessagesResponse',
  'EventsResponse',
  'KnownEvent',
  'EventEnvelope',
  'SnapshotResponse',
  'QuestionsResponse',
  'QuestionResponse',
  'ImageReference',
  'TextReference',
  'DocumentReference',
  'DocumentPage',
  'DocumentNavigation',
  'InputCapabilities',
  'ImageSettingsResponse',
  'WorkspaceFileResponse',
  'ModelCatalogResponse',
  'ModelBatchResponse',
]
const ajv = new Ajv2020({
  strict: false,
  allErrors: false,
  inlineRefs: false,
  code: { source: true, esm: true, lines: true },
})
ajv.addSchema({ $id: 'maigokite-wire', components: document.components })
const exports = Object.fromEntries(
  names.map((name) => {
    if (!document.components.schemas[name]) throw new Error(`Missing API schema: ${name}`)
    return [`validate${name}`, `maigokite-wire#/components/schemas/${name}`]
  }),
)
// Bundle Ajv's tiny runtime helpers as well; browsers need neither eval nor a
// runtime schema compiler. The generator dependencies remain development-only.
const validators = await build({
  stdin: { contents: standalone(ajv, exports), resolveDir: web, sourcefile: 'wire-validators.js' },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  write: false,
  minify: true,
})
const target = path.join(web, 'src/api/generated')
await mkdir(target, { recursive: true })
const header = '// Generated by npm run generate:contracts; do not edit manually.\n'
await writeFile(
  path.join(target, 'transport.d.ts'),
  header + astToString(await openapiTS(document)),
)
await writeFile(path.join(target, 'validators.js'), header + validators.outputFiles[0].text)
await writeFile(
  path.join(target, 'validators.d.ts'),
  header +
    "import type { components } from './transport'\n" +
    names
      .map(
        (name) =>
          `export function validate${name}(value: unknown): value is components['schemas']['${name}'];`,
      )
      .join('\n') +
    '\n',
)
console.log('Generated transport types and response validators from FastAPI OpenAPI.')
